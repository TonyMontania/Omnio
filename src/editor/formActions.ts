// Editor form actions — pure setter-driven helpers extracted from App.tsx
// (Fase 2.1). `resetForm` clears every editable field back to its default,
// and `loadItemIntoForm` pours an existing `AnyItem` into the same fields.
//
// Both take a `FormSetters` bag — one setter per FormSnapshot field, plus
// two extras (`setActiveCategory`, `setEditingId`) that loadItemIntoForm
// touches because loading an item also selects its category.
//
// Same pattern as buildItemFromForm: no closures over App.tsx state, no
// side effects beyond the setters passed in. Rust port is a matching set
// of `impl Default for FormState` / `impl From<&Item> for FormState`.

import type { Dispatch, SetStateAction } from 'react'
import type { AnyItem } from '../types'
import type { FormSnapshot } from './buildItemFromForm'

// One setter per snapshot field. `useState<T>()` returns a
// `Dispatch<SetStateAction<T>>`, so this shape drops in unchanged
// against App.tsx's existing useState declarations.
export type FormSetters = {
  [K in keyof FormSnapshot as `set${Capitalize<K & string>}`]: Dispatch<SetStateAction<FormSnapshot[K]>>
} & {
  // Extras — loadItemIntoForm also records the edit id. setActiveCategory
  // is auto-generated by the mapped type above because `activeCategory`
  // is a FormSnapshot field (typed as CategoryId in Fase 3.3).
  setEditingId: Dispatch<SetStateAction<string | null>>
}

